#!/usr/bin/env python3
"""
page-dates  1012 V1
The dated registry of hand-built pages — the sections whose pages are single
.astro files with no data file to hold a date (American Idolatry, Sun Worship,
Catholicism, the Holidays, Foreign Fire, Disney, the Calendar, Hebrew, /studies).
Dutch's 1012 rule: every undated piece takes the day it was first committed to
the site. Writes src/data/page-dates.json, which src/lib/home-pieces.js reads for
the homepage's Last 30 Days.

For each page: route, section (a SECTIONS key in series-skins.js), date (first
commit of its source file, git log --follow), title (its <h1>), deck (the line
the page renders under its title — the same element the social-card generator
reads; empty when the page has none, never the meta description).

Run after `npm run build` whenever a page is added to one of these sections:
  python3 scripts/page-dates.py
Pages whose source file has no commit yet are listed on stderr and left out.
"""

import glob
import importlib.util
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
OUT = os.path.join(ROOT, "src", "data", "page-dates.json")

# source folder under src/pages → SECTIONS key the pages file under
SECTION_DIRS = {
    "american-idolatry": "american-idolatry",
    "sun-worship": "sun-worship",
    "catholicism": "catholicism",
    "holidays": "holidays",
    "foreign-fire": "foreign-fire",
    "disney": "hollywood",
    "calendar": "calendar",
    "hebrew": "hebrew",
    "studies": "berean-studies",
}

spec = importlib.util.spec_from_file_location("backfill", os.path.join(HERE, "backfill-social-images.py"))
bf = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bf)


def first_commit(path):
    out = subprocess.run(
        ["git", "log", "--follow", "--diff-filter=A", "--format=%ad", "--date=short", "--", path],
        cwd=ROOT, capture_output=True, text=True,
    ).stdout.split()
    return out[-1] if out else None


def main():
    rows, missing = [], []
    for folder, section in SECTION_DIRS.items():
        for src in sorted(glob.glob(os.path.join(ROOT, "src", "pages", folder, "**", "*.astro"), recursive=True)):
            name = os.path.basename(src)
            if name.startswith("["):
                continue  # dynamic routes are dated through their own data
            rel = os.path.relpath(src, os.path.join(ROOT, "src", "pages"))[: -len(".astro")]
            rel = re.sub(r"(^|/)index$", "", rel)
            built = os.path.join(ROOT, "dist", rel, "index.html")
            if not os.path.exists(built):
                continue
            page = open(built, encoding="utf-8").read()
            m = bf.H1.search(page)
            if not m:
                continue  # no title, no card on the homepage
            date = first_commit(os.path.relpath(src, ROOT))
            if not date:
                missing.append("/" + rel)
                continue
            rows.append({
                "route": "/" + rel,
                "section": section,
                "date": date,
                "title": bf.text(m.group(1)),
                "deck": bf.rendered_deck(page, rel) or "",
            })
    rows.sort(key=lambda r: r["route"])
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({"note": "Generated by scripts/page-dates.py — do not hand-edit.", "pages": rows}, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"page-dates: {len(rows)} pages dated → src/data/page-dates.json")
    for r in missing:
        print(f"  no commit date: {r}", file=sys.stderr)


if __name__ == "__main__":
    main()
